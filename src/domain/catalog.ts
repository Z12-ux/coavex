const CATALOGS: Record<Locale, Catalog> = { fr, en, ar };

/** Translate an engine key. Falls back to French, then to the key itself. */
export function tx(locale: Locale, key: string, params: Params = {}): string {
  const entry = CATALOGS[locale]?.[key] ?? CATALOGS.fr[key];
  if (entry === undefined) return key;
  return typeof entry === "function" ? entry(params) : entry;
}

export function hasKey(key: string): boolean {
  return key in fr;
}
