const DICTS: Record<Locale, Partial<Record<DictKey, string>>> = { fr, en, ar };

export function t(locale: Locale, key: DictKey | string): string {
  const k = key as DictKey;
  return DICTS[locale]?.[k] ?? fr[k] ?? key;
}

export function dirFor(locale: Locale): "rtl" | "ltr" {
  return locale === "ar" ? "rtl" : "ltr";
}

export function isLocale(x: unknown): x is Locale {
  return x === "fr" || x === "ar" || x === "en";
}
